  let lang = 'kz';
  try { lang = localStorage.getItem('nlrk_lang') === 'ru' ? 'ru' : 'kz'; } catch (e) { /* */ }
  const listeners = [];

  function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]) || DICT.kz[key] || key;
    if (vars) Object.keys(vars).forEach(k => { s = s.split('{' + k + '}').join(vars[k]); });
    return s;
  }

  // Басқа тілдегі мәтін (құлып экранында екі тілде көрсету үшін)
  function tOther(key, vars) {
    const prev = lang;
    lang = lang === 'kz' ? 'ru' : 'kz';
    const s = t(key, vars);
    lang = prev;
    return s;
  }

  function apply(root) {
    root = root || document;
    document.documentElement.lang = lang === 'ru' ? 'ru' : 'kk';
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
    root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); el.setAttribute('aria-label', el.title); });
    document.querySelectorAll('.lang-switch button').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));
  }

  function set(l) {
    lang = l === 'ru' ? 'ru' : 'kz';
    try { localStorage.setItem('nlrk_lang', lang); } catch (e) { /* */ }
    apply();
    listeners.forEach(fn => fn(lang));
  }

  window.I18n = {
    t: t, tOther: tOther, apply: apply, set: set,
    get lang() { return lang; },
    onChange: fn => listeners.push(fn)
  };
